import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { promisify } from 'node:util';
import { CATALOG_PRODUCTS } from '../src/catalog.ts';
import { PREMIUM_PRODUCTS } from '../src/premium-catalog.ts';

// Cache openly licensed product photos without changing the photographed labels.
// Run on macOS with Node 22+: node --experimental-strip-types scripts/cache-catalog-photos.mjs
const exec = promisify(execFile);
const root = path.join(import.meta.dirname, '..');
const output = path.join(root, 'assets', 'catalogue');
const fullSize = /\.(?:200|400)\.jpg$/i;
const products = [...new Map([...CATALOG_PRODUCTS, ...PREMIUM_PRODUCTS].map(product => [product.imageUrl, product])).values()];
const work = await mkdtemp(path.join(tmpdir(), 'bottleflow-photos-'));
const failures = [];
let index = 0;

async function cachePhoto({ imageUrl }) {
  const hash = createHash('sha256').update(imageUrl).digest('hex').slice(0, 12);
  const filename = `${hash}.jpg`;
  const asset = path.join(output, filename);
  const original = path.join(work, filename);
  // Only the catalogue's licensed Open Food Facts images are copied into the app.
  if (new URL(imageUrl).hostname !== 'images.openfoodfacts.org') throw new Error('Unexpected image source');
  try {
    await readFile(asset);
    return [imageUrl, filename];
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  const variants = new Set([imageUrl.replace(fullSize, '.full.jpg'), imageUrl]);
  for (const url of variants) {
    const response = await fetch(url, { signal: AbortSignal.timeout(12000) });
    if (!response.ok || !response.headers.get('content-type')?.startsWith('image/')) continue;
    await writeFile(original, Buffer.from(await response.arrayBuffer()));
    await exec('sips', ['-Z', '1080', '-s', 'format', 'jpeg', '-s', 'formatOptions', '85', original, '--out', asset]);
    return [imageUrl, filename];
  }
  throw new Error('No usable front photo');
}

try {
  await mkdir(output, { recursive: true });
  const batches = await Promise.all(Array.from({ length: 6 }, async () => {
    const cached = [];
    while (index < products.length) {
      const product = products[index++];
      try {
        cached.push(await cachePhoto(product));
      } catch (error) {
        failures.push(`${product.sku} ${product.name}: ${error.message}`);
      }
    }
    return cached;
  }));
  const cached = batches.flat().sort(([a], [b]) => a.localeCompare(b));
  if (cached.length === 0) throw new Error('No photos cached. Check network access and try again.');
  const entries = cached.map(([url, filename]) => `  ${JSON.stringify(url)}: require('../assets/catalogue/${filename}'),`);
  await writeFile(path.join(root, 'src', 'catalog-photos.ts'), [
    '// Generated by scripts/cache-catalog-photos.mjs. See docs/OPEN_DATA_ATTRIBUTION.md.',
    'export const CATALOG_PHOTOS: Readonly<Record<string, number | undefined>> = {',
    ...entries,
    '};',
    '',
  ].join('\n'));
  console.log(`Cached ${cached.length}/${products.length} real product photos.`);
  if (failures.length) {
    console.error(failures.join('\n'));
    process.exitCode = 1;
  }
} finally {
  await rm(work, { recursive: true, force: true });
}
